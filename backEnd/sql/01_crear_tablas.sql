DROP TABLE IF EXISTS inscripciones CASCADE CONSTRAINTS PURGE;
DROP TABLE IF EXISTS clases        CASCADE CONSTRAINTS PURGE;
DROP TABLE IF EXISTS socios        CASCADE CONSTRAINTS PURGE;
DROP TABLE IF EXISTS instructores  CASCADE CONSTRAINTS PURGE;
DROP TABLE IF EXISTS planes        CASCADE CONSTRAINTS PURGE;

CREATE TABLE planes (
    id_plan           NUMBER(11) GENERATED BY DEFAULT ON NULL AS IDENTITY (NOCACHE),
    nombre            VARCHAR2(50)  NOT NULL,
    descripcion       VARCHAR2(200),
    precio_mensual    NUMBER(10,2)  NOT NULL,
    clases_por_semana NUMBER(2)     NOT NULL,
    precio_anual      NUMBER(12,2)  GENERATED ALWAYS AS (precio_mensual * 12) VIRTUAL,
    CONSTRAINT pk_planes        PRIMARY KEY (id_plan),
    CONSTRAINT uq_planes_nombre UNIQUE (nombre),
    CONSTRAINT ck_planes_precio CHECK (precio_mensual >= 0),
    CONSTRAINT ck_planes_clases CHECK (clases_por_semana > 0)
);

CREATE TABLE instructores (
    id_instructor NUMBER(11) GENERATED BY DEFAULT ON NULL AS IDENTITY (NOCACHE),
    rut           VARCHAR2(12)  NOT NULL,
    nombre        VARCHAR2(100) NOT NULL,
    especialidad  VARCHAR2(80)  NOT NULL,
    email         VARCHAR2(100),
    telefono      VARCHAR2(20),
    usuario       VARCHAR2(150),
    activo        NUMBER(1)     DEFAULT 1 NOT NULL,
    CONSTRAINT pk_instructores         PRIMARY KEY (id_instructor),
    CONSTRAINT uq_instructores_rut     UNIQUE (rut),
    CONSTRAINT uq_instructores_email   UNIQUE (email),
    CONSTRAINT uq_instructores_usuario UNIQUE (usuario),
    CONSTRAINT ck_instructores_activo  CHECK (activo IN (0, 1))
);

CREATE TABLE socios (
    id_socio          NUMBER(11) GENERATED BY DEFAULT ON NULL AS IDENTITY (NOCACHE),
    rut               VARCHAR2(12)  NOT NULL,
    nombre            VARCHAR2(100) NOT NULL,
    email             VARCHAR2(100),
    telefono          VARCHAR2(20),
    id_plan           NUMBER(11)    NOT NULL,
    fecha_vencimiento DATE          NOT NULL,
    activo            NUMBER(1)     DEFAULT 1 NOT NULL,
    fecha_registro    TIMESTAMP     DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
    CONSTRAINT pk_socios        PRIMARY KEY (id_socio),
    CONSTRAINT uq_socios_rut    UNIQUE (rut),
    CONSTRAINT uq_socios_email  UNIQUE (email),
    CONSTRAINT fk_socios_plan   FOREIGN KEY (id_plan) REFERENCES planes (id_plan),
    CONSTRAINT ck_socios_activo CHECK (activo IN (0, 1))
);

CREATE TABLE clases (
    id_clase      NUMBER(11) GENERATED BY DEFAULT ON NULL AS IDENTITY (NOCACHE),
    id_instructor NUMBER(11)    NOT NULL,
    nombre        VARCHAR2(100) NOT NULL,
    descripcion   VARCHAR2(200),
    fecha_hora    TIMESTAMP     NOT NULL,
    cupo_maximo   NUMBER(3)     NOT NULL,
    estado        VARCHAR2(10)  DEFAULT 'programada' NOT NULL,
    CONSTRAINT pk_clases            PRIMARY KEY (id_clase),
    CONSTRAINT fk_clases_instructor FOREIGN KEY (id_instructor) REFERENCES instructores (id_instructor),
    CONSTRAINT ck_clases_cupo       CHECK (cupo_maximo > 0),
    CONSTRAINT ck_clases_estado     CHECK (estado IN ('programada', 'realizada', 'suspendida'))
);

CREATE TABLE inscripciones (
    id_clase          NUMBER(11) NOT NULL,
    id_socio          NUMBER(11) NOT NULL,
    fecha_inscripcion TIMESTAMP  DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
    asistio           NUMBER(1)  DEFAULT 0 NOT NULL,
    CONSTRAINT pk_inscripciones         PRIMARY KEY (id_clase, id_socio),
    CONSTRAINT fk_inscripciones_clase   FOREIGN KEY (id_clase) REFERENCES clases (id_clase) ON DELETE CASCADE,
    CONSTRAINT fk_inscripciones_socio   FOREIGN KEY (id_socio) REFERENCES socios (id_socio),
    CONSTRAINT ck_inscripciones_asistio CHECK (asistio IN (0, 1))
);

CREATE INDEX ix_socios_plan         ON socios (id_plan);
CREATE INDEX ix_clases_instructor   ON clases (id_instructor);
CREATE INDEX ix_inscripciones_socio ON inscripciones (id_socio);
